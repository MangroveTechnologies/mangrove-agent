"""Write server/requirements-custody.lock: the pins of server/requirements.lock with wheel hashes.

The custody installer installs this file with ``pip --require-hashes
--only-binary :all:``, so pip installs only wheels whose SHA-256 is listed
here and never builds a source distribution (whose build dependencies would be
fetched without hash checks). Every wheel PyPI publishes for a pinned version
is listed, so the same file installs on Linux and macOS. A pin with no wheel is
an error. Run it after changing requirements.lock:

    python3 scripts/hash_custody_lock.py

``--check`` verifies offline that the hashed file holds exactly the lock's
pins. ``--verify`` regenerates the file from PyPI in memory and fails on any
difference, so the hashes cannot drift silently.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / 'server/requirements.lock'
HASHED = ROOT / 'server/requirements-custody.lock'
PIN = re.compile(r'^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;#\\]+)\s*(?:;\s*([^#\\]*?))?\s*\\?\s*$')


def pins(path: Path) -> list[tuple[str, str, str]]:
    """(name, version, environment marker) for every pinned requirement."""
    found = []
    for line in path.read_text().splitlines():
        match = PIN.match(line.strip())
        if match:
            found.append((match.group(1).lower(), match.group(2), (match.group(3) or '').strip()))
    return found


def hashes(name: str, version: str) -> list[str]:
    url = f'https://pypi.org/pypi/{name}/{version}/json'
    with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 - fixed PyPI origin
        files = json.load(response)['urls']
    digests = sorted({item['digests']['sha256'] for item in files if item['packagetype'] == 'bdist_wheel'})
    if not digests:
        raise ValueError(f'PyPI lists no wheel for {name}=={version}; custody installs wheels only')
    return digests


def render(entries: list[tuple[str, str, str]]) -> str:
    lines = ['# Generated by scripts/hash_custody_lock.py from server/requirements.lock. Do not edit.',
             '# Installed by scripts/install-custody.py with pip --require-hashes --only-binary :all:.']
    for name, version, marker in entries:
        digests = hashes(name, version)
        lines.append(f'{name}=={version}' + (f' ; {marker}' if marker else '') + ' \\')
        lines.extend(f'    --hash=sha256:{digest}' + (' \\' if index < len(digests) - 1 else '')
                     for index, digest in enumerate(digests))
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    expected = sorted(pins(LOCK))
    if args.verify:
        if not HASHED.is_file() or HASHED.read_text() != render(expected):
            print('server/requirements-custody.lock differs from a fresh render of requirements.lock '
                  'and PyPI wheel hashes; run python3 scripts/hash_custody_lock.py and review the diff',
                  file=sys.stderr)
            return 1
        print('Custody hashed lock matches a fresh render from PyPI.')
        return 0
    if args.check:
        if not HASHED.is_file() or sorted(pins(HASHED)) != expected:
            print('server/requirements-custody.lock does not match server/requirements.lock; '
                  'run python3 scripts/hash_custody_lock.py', file=sys.stderr)
            return 1
        print('Custody hashed lock matches requirements.lock.')
        return 0
    HASHED.write_text(render(expected))
    print(f'Wrote {HASHED.relative_to(ROOT)} with {len(expected)} hashed pins.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
