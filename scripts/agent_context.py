"""Render the shared agent policy for clients without repository file access.

Only reviewed, local client instructions are bundled. Server-owned strategy
skills must still be loaded live over MCP. This module never reads credentials
or contacts the agent, upstream services, or a model.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    'SAGE.md',
    '.claude/rules/trading-bot-workflow.md',
    '.claude/rules/wallet-presentation.md',
    '.claude/rules/risk-management.md',
)
BUNDLE = Path('docs/clients/sage-instructions.md')


def render_context(root: Path = ROOT) -> str:
    parts = [
        '# Mangrove agent - complete client instructions\n\n'
        'Generated by `python3 scripts/agent_context.py`. Do not edit this export.\n'
        'Edit SAGE.md or its mandatory rule sources, then regenerate.\n\n'
        'All SOURCE sections below are already loaded instructions. They are the\n'
        'same shared policy read by repository clients. Local source paths identify\n'
        'provenance; a host without file access must not attempt to open them.\n'
        'This bundle does not install tools, grant access, or include server-owned\n'
        'strategy skills. Discover and verify the actual Mangrove MCP connection\n'
        'before claiming operational access. Respect the host instruction hierarchy.\n'
    ]
    for relative in SOURCES:
        source = (root / relative).read_bytes()
        # Preserve policy wording while making the export safe for plain-text
        # instruction fields. Hashes identify the original UTF-8 source bytes.
        content = source.decode('utf-8').translate(str.maketrans({'\u2014': '--', '\u03a3': 'sum'})).rstrip()
        digest = hashlib.sha256(source).hexdigest()
        parts.append(f'## SOURCE: {relative}\n\n<!-- sha256: {digest} -->\n\n{content}\n')
    return '\n---\n\n'.join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='Fail if the checked-in export is stale.')
    mode.add_argument('--stdout', action='store_true', help='Print complete instructions for host injection.')
    args = parser.parse_args()
    try:
        content = render_context()
        if args.stdout:
            print(content, end='')
        elif args.check:
            if not (ROOT / BUNDLE).is_file() or (ROOT / BUNDLE).read_text() != content:
                print('Agent client bundle is stale; run python3 scripts/agent_context.py.', file=sys.stderr)
                return 1
            print('Agent client bundle matches all shared policy sources.')
        else:
            (ROOT / BUNDLE).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / BUNDLE).write_text(content)
            print(f'Generated {BUNDLE}. No credentials or server skills were included.')
    except (OSError, UnicodeError):
        print('Cannot load the complete agent instructions; repair the installation.', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
